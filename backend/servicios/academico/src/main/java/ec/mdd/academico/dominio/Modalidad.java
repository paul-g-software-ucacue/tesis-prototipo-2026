package ec.mdd.academico.dominio;

/** Modalidad de estudios de una carrera (glosario, RRA art. 54, carga 2). */
public enum Modalidad {
    /** Presencial. */
    PRESENCIAL,
    /** Semipresencial. */
    SEMIPRESENCIAL,
    /** En línea. */
    EN_LINEA,
    /** A distancia. */
    A_DISTANCIA,
    /** Dual. */
    DUAL,
    /** Híbrida. */
    HIBRIDA
}

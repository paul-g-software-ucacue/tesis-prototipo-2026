/**
 * Categoría y nivel de un docente titular (glosario «Categoría de escalafón», carga 6); los demás
 * tipos llevan {@link #NO_APLICA}.
 */
public enum CategoriaDeEscalafon {
    AUXILIAR_1,
    AUXILIAR_2,
    AGREGADO_1,
    AGREGADO_2,
    AGREGADO_3,
    PRINCIPAL_1,
    PRINCIPAL_2,
    PRINCIPAL_3,
    NO_APLICA
}

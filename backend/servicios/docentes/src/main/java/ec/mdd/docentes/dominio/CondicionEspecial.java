package ec.mdd.docentes.dominio;

/**
 * Condición que cambia las horas que le corresponden a un docente (glosario «Condición especial»,
 * RN-14 a RN-16, C-02). Cuánto las cambia lo dice la normativa.
 */
public enum CondicionEspecial {
    CUIDADOR_SUSTITUTO,
    MATERNIDAD_LACTANCIA,
    APOYO_SIES,
    NINGUNA
}
